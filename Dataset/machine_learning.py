import pandas as pd
import re
from sklearn.feature_extraction.text import CountVectorizer
from sklearn.preprocessing import OneHotEncoder
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.model_selection import train_test_split
from sklearn.utils import resample
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, classification_report, confusion_matrix
import matplotlib.pyplot as plt
import seaborn as sns
from google.colab import drive

drive.mount('/content/drive')
df = pd.read_csv("/content/drive/MyDrive/Master/ML/labeled_logs.csv")

total_entries = len(df)

normal_entries = (df['Label'] == 0).sum()
malicious_entries = (df['Label'] == 1).sum()

print(f"Total entries: {total_entries}")
print(f"Normal entries (Label = 0): {normal_entries}")
print(f"Malicious entries (Label = 1): {malicious_entries}")

print(f"Normal percentage: {normal_entries/total_entries*100:.2f}%")
print(f"Malicious percentage: {malicious_entries/total_entries*100:.2f}%")

df["Log"] = df["Log"].str.replace(r"^\w{3}\s+\d{2}\s+\d{2}:\d{2}:\d{2}\s+", "", regex=True)

df_majority = df[df.Label == 0]
df_minority = df[df.Label == 1]


def extract_custom_features(df):
    df['ip_count'] = df['Log'].str.count(r"\b(?:\d{1,3}\.){3}\d{1,3}\b")
    df['has_user'] = df['Log'].str.contains(r"user\s*=\s*\w+|uid\s*=\d+|user\s+\w+|plcnext_firmware|ejub|admin", flags=re.IGNORECASE, regex=True).astype(int)
    df['has_process'] = df['Log'].str.contains(r"\b(process|application|daemon|kernel|crond|ntpd|su|dbus-daemon)\b", flags=re.IGNORECASE, regex=True).astype(int)
    df['has_command'] = df['Log'].str.contains(r"comm=\"[^\"]+\"|command:\s*\w+|su for|status", flags=re.IGNORECASE, regex=True).astype(int)
    df['file_path_count'] = df['Log'].str.count(r"(/\w+)+")
    df['has_error'] = df['Log'].str.contains(r"error|failed|denied", flags=re.IGNORECASE, regex=True).astype(int)
    df['has_timestamp'] = df['Log'].str.contains(r"\b\d{2}:\d{2}:\d{2}\b", regex=True).astype(int)
    df['has_event_type'] = df['Log'].str.contains(r"INFO|DEBUG|ERROR|WARN", flags=re.IGNORECASE, regex=True).astype(int)
    df['port_count'] = df['Log'].str.count(r":\d{2,5}")
    df['has_protocol'] = df['Log'].str.contains(r"\b(TCP|UDP|IP|IPv6)\b", flags=re.IGNORECASE, regex=True).astype(int)
    return df

df = extract_custom_features(df)

y = df["Label"]

vectorizer = CountVectorizer(
    max_features=1000,
    stop_words="english",
    lowercase=True
)
X_text_vec = vectorizer.fit_transform(df["Log"])

structured_features = [
    "ip_count", "has_user", "has_process", "has_command",
    "file_path_count", "has_error", "has_timestamp",
    "has_event_type", "port_count", "has_protocol"
]
X_struct = df[structured_features].reset_index(drop=True)

X_final = pd.concat([
    pd.DataFrame(X_text_vec.toarray(), columns=vectorizer.get_feature_names_out()),
    X_struct
], axis=1)

X_train, X_test, y_train, y_test = train_test_split(X_final, y, test_size=0.2, random_state=42)

print("Total features:", X_final.shape[1])
print("Training set shape:", X_train.shape)
print("Test set shape:", X_test.shape)

clf = RandomForestClassifier(
    n_estimators=100,
    max_depth=None,
    class_weight='balanced',
    random_state=42,
    n_jobs=-1
)
clf.fit(X_train, y_train)

y_pred = clf.predict(X_test)

accuracy = accuracy_score(y_test, y_pred)
precision = precision_score(y_test, y_pred, zero_division=0)
recall = recall_score(y_test, y_pred, zero_division=0)
f1 = f1_score(y_test, y_pred, zero_division=0)

print("Random Forest Evaluation Results:")
print(f"Accuracy : {accuracy:.4f}")
print(f"Precision: {precision:.4f}")
print(f"Recall   : {recall:.4f}")
print(f"F1 Score : {f1:.4f}")
print("\nClassification Report:")

cm = confusion_matrix(y_test, y_pred)
plt.figure(figsize=(6, 4))
sns.heatmap(cm, annot=True, fmt="d", cmap="Blues",
            xticklabels=["Benign", "Malicious"],
            yticklabels=["Benign", "Malicious"])
plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.title("Confusion Matrix")
plt.tight_layout()
plt.show()