def compare_memory_usage_single(df, name):
    stats = []

    def fit_slope(x, y):
        m, b = np.polyfit(x, y, 1)
        return m, b

    def convert_to_kb(bytes_value):
        return bytes_value / 1024

    df['Time_Since_Start_Minutes'] = (df['datetime'] - df['datetime'].min()).dt.total_seconds() / 60

    df['MEM_USED_KB'] = df['Arp.Plc.Eclr/code.USER_PART_DT.MEM_USED'].apply(convert_to_kb)
    df['MEM_TOTAL_KB'] = df['Arp.Plc.Eclr/code.USER_PART_DT.MEM_TOTAL'].apply(convert_to_kb)

    used_memory_rate = (df['MEM_USED_KB'].diff().mean()) / (df.index[1] - df.index[0]) if len(df) > 1 else 0

    initial_used_kb = df['MEM_USED_KB'].iloc[0]
    initial_total_kb = df['MEM_TOTAL_KB'].iloc[0]
    initial_memory_percent = (initial_used_kb / initial_total_kb) * 100

    stats.append({
        'Scenario': name,
        'Used Memory Rate (KB/min)': used_memory_rate,
        'Initial Memory Used (KB)': initial_used_kb,
        'Initial Memory Used (%)': round(initial_memory_percent, 2)
    })

    stats_df = pd.DataFrame(stats)
    print(stats_df)

