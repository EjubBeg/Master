def compare_cycle_times_single(df, name):
    stats = []

    df['Time_Since_Start_Minutes'] = (df['datetime'] - df['datetime'].min()).dt.total_seconds() / 60
    df['Total_Exec_Duration'] = df['Total_Exec_Duration'] / 2

    stats.append({
        'Name': name,
        'Mean': df['Total_Exec_Duration'].mean(),
        'Max': df['Total_Exec_Duration'].max(),
        'Std': df['Total_Exec_Duration'].std(),
    })

    stats_df = pd.DataFrame(stats)
    print(stats_df)

    cmap = plt.get_cmap("coolwarm")

    plt.figure(figsize=(14, 8))
    colors = cmap(df['Total_Exec_Duration'] / df['Total_Exec_Duration'].max())
    plt.scatter(df['Time_Since_Start_Minutes'], df['Total_Exec_Duration'], color=colors, alpha=0.7)
    plt.plot(df['Time_Since_Start_Minutes'], df['Total_Exec_Duration'].rolling(window=200).mean(), color='black', linestyle='--')
    plt.title(f"{name} Cycle Time Over Time", fontsize=16)
    plt.ylabel('Cycle Time (ms)', fontsize=14)
    plt.xlabel('Time Since Start (minutes)', fontsize=14)
    plt.grid(True)
    plt.legend(fontsize=12)
    plt.tight_layout()
    plt.show()

